// The console's API contract: a checked-in OpenAPI snapshot of the outlabs-auth library routes,
// and the TypeScript wire types generated from it (app/types/api.gen.ts).
//
// The snapshot keeps only operations the library itself mounts. Every library operation carries
// the `x-outlabs-auth-surface` extension (the surface names /auth/config reports under
// mounted_surfaces); host routes an example app adds (health checks, demo resources) do not, so
// they are dropped along with the schemas only they use. Paths are stored relative to the auth
// API prefix, the same form the console's API client uses.

export const SURFACE_EXTENSION = 'x-outlabs-auth-surface'
export const PRESETS_EXTENSION = 'x-outlabs-auth-presets'
export const HTTP_METHODS = ['get', 'put', 'post', 'delete', 'patch', 'options', 'head']

function isRecord(value) {
  return value != null && typeof value === 'object' && !Array.isArray(value)
}

function sortObject(value) {
  return Object.fromEntries(Object.entries(value).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)))
}

function stripPrefix(path, prefix) {
  if (!prefix) return path
  return path === prefix ? '/' : path.startsWith(`${prefix}/`) ? path.slice(prefix.length) : null
}

// Every `#/components/schemas/<name>` reachable from `value`, following schemas transitively.
function collectSchemaRefs(value, schemas, found = new Set()) {
  if (Array.isArray(value)) {
    for (const item of value) collectSchemaRefs(item, schemas, found)
    return found
  }
  if (!isRecord(value)) return found
  for (const [key, child] of Object.entries(value)) {
    if (key === '$ref' && typeof child === 'string' && child.startsWith('#/components/schemas/')) {
      const name = child.slice('#/components/schemas/'.length)
      if (!found.has(name)) {
        found.add(name)
        if (schemas[name]) collectSchemaRefs(schemas[name], schemas, found)
      }
    } else {
      collectSchemaRefs(child, schemas, found)
    }
  }
  return found
}

function libraryOperation(operation) {
  if (!isRecord(operation) || !Array.isArray(operation[SURFACE_EXTENSION])) return null
  // Tags are presentation only and differ between host apps; they would churn the snapshot.
  const copy = { ...operation }
  delete copy.tags
  return copy
}

/**
 * Merge one or more /openapi.json documents into the library snapshot.
 *
 * @param {Array<{ preset: string, spec: object }>} sources - a spec per example preset
 * @param {{ prefix?: string, version: string, source?: string }} options
 */
export function buildSnapshot(sources, { prefix = '/v1', version, source = '' } = {}) {
  if (!version) throw new Error('buildSnapshot: a library version is required')
  /** @type {Record<string, Record<string, any>>} */
  const paths = {}
  /** @type {Record<string, any>} */
  const allSchemas = {}
  /** @type {string[]} */
  const conflicts = []

  for (const { preset, spec } of sources) {
    const schemas = spec?.components?.schemas ?? {}
    for (const [name, schema] of Object.entries(schemas)) {
      if (allSchemas[name] && JSON.stringify(allSchemas[name]) !== JSON.stringify(schema)) conflicts.push(`schema ${name}`)
      allSchemas[name] ??= schema
    }
    for (const [rawPath, item] of Object.entries(spec?.paths ?? {})) {
      const path = stripPrefix(rawPath, prefix)
      if (!path || !isRecord(item)) continue
      for (const method of HTTP_METHODS) {
        const operation = libraryOperation(item[method])
        if (!operation) continue
        const target = (paths[path] ??= {})
        if (target[method] && JSON.stringify(target[method]) !== JSON.stringify(operation)) conflicts.push(`${method.toUpperCase()} ${path}`)
        target[method] ??= operation
        const presets = new Set(target[PRESETS_EXTENSION] ?? [])
        presets.add(preset)
        target[PRESETS_EXTENSION] = [...presets].sort()
      }
    }
  }

  /** @type {Record<string, Record<string, any>>} */
  const sortedPaths = {}
  for (const path of Object.keys(paths).sort()) {
    const item = paths[path]
    /** @type {Record<string, any>} */
    const ordered = {}
    for (const method of HTTP_METHODS) if (item[method]) ordered[method] = item[method]
    ordered[PRESETS_EXTENSION] = item[PRESETS_EXTENSION]
    sortedPaths[path] = ordered
  }

  const used = collectSchemaRefs(sortedPaths, allSchemas)
  const missing = [...used].filter(name => !allSchemas[name])
  if (missing.length) throw new Error(`buildSnapshot: unresolved schemas ${missing.join(', ')}`)
  const schemas = sortObject(Object.fromEntries([...used].map(name => [name, allSchemas[name]])))

  return {
    snapshot: {
      'openapi': '3.1.0',
      'info': {
        title: 'outlabs-auth',
        version,
        description: 'Library routes of outlabs-auth, relative to the auth API prefix. '
          + 'Generated by scripts/gen-api-types.mjs --refresh; do not edit by hand.'
      },
      'x-outlabs-auth-source': source,
      'paths': sortedPaths,
      'components': { schemas }
    },
    conflicts
  }
}

/** Every operation in a snapshot: { method (upper case), path, surfaces, presets }. */
export function snapshotRoutes(snapshot) {
  const routes = []
  for (const [path, item] of Object.entries(snapshot?.paths ?? {})) {
    for (const method of HTTP_METHODS) {
      const operation = item[method]
      if (!operation) continue
      routes.push({
        method: method.toUpperCase(),
        path,
        surfaces: [...(operation[SURFACE_EXTENSION] ?? [])],
        presets: [...(item[PRESETS_EXTENSION] ?? [])]
      })
    }
  }
  return routes
}

export const API_TYPES_HEADER = `/* eslint-disable */
// Generated by scripts/gen-api-types.mjs from openapi/outlabs-auth.openapi.json.
// Do not edit by hand: refresh the snapshot, then run \`bun run gen:api-types\`.
// Domain types in app/types/*.ts derive from these component schemas.
`

/** Render the TypeScript wire types for a snapshot (openapi-typescript). */
export async function renderApiTypes(snapshot) {
  const { default: openapiTS, astToString } = await import('openapi-typescript')
  const ast = await openapiTS(structuredClone(snapshot), {
    alphabetize: true,
    // Fields with a default are always present in responses (the API serializes defaults);
    // request input types in app/types keep such fields optional themselves.
    defaultNonNullable: true,
    silent: true
  })
  return `${API_TYPES_HEADER}\n${astToString(ast)}`
}
